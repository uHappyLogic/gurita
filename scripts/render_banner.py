"""Render the README banner SVG from its plain-text drawing and colour mapping.

Usage: uv run scripts/render_banner.py [DRAWING]

DRAWING defaults to assets/banner.txt. Its colour mapping is read from the file beside it
named <stem>-colors.txt, and the SVG is written beside both as <stem>.svg, so the committed
SVG is derived output of the drawing and is regenerated by re-running this script, never
edited by hand.

The drawing is plain text, one grid row per line, using only the 95 printable 7-bit ASCII
characters (U+0020 to U+007E); a shorter line is padded with spaces to the widest one.

The colour mapping opens with legend lines, each a one-character key and a #rrggbb colour
separated by whitespace, ended by the first blank line; below it stands a mask grid of the
drawing's shape, where the cell under every non-space drawing character holds the key of that
character's colour. Cells under a space are ignored, and a shorter mask line reads as spaces.

The SVG has no background fill and draws every character as text in a system monospace font
stack, with no font embedded and no glyph converted to paths: each row is one text element
whose characters sit in tspan runs carrying an explicit x coordinate per column, so the grid
holds whatever advance widths the viewer's font has. The output depends on the two input files
alone, so every run writes the same bytes.

This script is stdlib-only and runs under Python 3.9 and later. It only reads its two inputs
and writes its one output; it never invokes git.
"""

import argparse
import os
import re
import sys

DEFAULT_DRAWING = os.path.join("assets", "banner.txt")

CELL_WIDTH = 10
ROW_HEIGHT = 20
FONT_SIZE = 16
BASELINE = 15
FONT_STACK = (
    "ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, "
    "'Liberation Mono', 'DejaVu Sans Mono', 'Courier New', monospace"
)

COLOUR_PATTERN = re.compile(r"^#[0-9a-fA-F]{6}$")


class BannerError(Exception):
    """The drawing or its colour mapping cannot be rendered."""


def split_lines(text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def parse_drawing(text):
    rows = split_lines(text)
    while rows and not rows[-1].strip(" "):
        rows.pop()
    if not rows:
        raise BannerError("the drawing is empty")
    for number, row in enumerate(rows, 1):
        for column, char in enumerate(row, 1):
            if not " " <= char <= "~":
                raise BannerError(
                    f"drawing row {number}, column {column}: {char!r} is not a printable "
                    "7-bit ASCII character (U+0020 to U+007E)"
                )
    width = max(len(row) for row in rows)
    return [row.ljust(width) for row in rows]


def parse_colours(text):
    lines = split_lines(text)
    legend = {}
    index = 0
    while index < len(lines) and lines[index].strip():
        parts = lines[index].split()
        if len(parts) != 2 or len(parts[0]) != 1 or not COLOUR_PATTERN.match(parts[1]):
            raise BannerError(
                f"colour mapping line {index + 1}: expected a one-character key and a "
                f"#rrggbb colour, got {lines[index]!r}"
            )
        key, colour = parts
        if key in legend:
            raise BannerError(f"colour mapping line {index + 1}: key {key!r} defined twice")
        legend[key] = colour.lower()
        index += 1
    if not legend:
        raise BannerError("the colour mapping has no legend lines")
    mask = lines[index + 1:]
    return legend, mask


def colour_grid(rows, legend, mask):
    grid = []
    for number, row in enumerate(rows):
        mask_row = mask[number] if number < len(mask) else ""
        colours = []
        for column, char in enumerate(row):
            if char == " ":
                colours.append(None)
                continue
            key = mask_row[column] if column < len(mask_row) else " "
            if key not in legend:
                raise BannerError(
                    f"drawing row {number + 1}, column {column + 1}: {char!r} has no colour "
                    f"(mask cell {key!r} is not a legend key)"
                )
            colours.append(legend[key])
        grid.append(colours)
    return grid


def escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render(drawing_text, colours_text):
    """Return the banner SVG for one drawing and its colour mapping, as text."""
    rows = parse_drawing(drawing_text)
    legend, mask = parse_colours(colours_text)
    grid = colour_grid(rows, legend, mask)
    width = len(rows[0]) * CELL_WIDTH
    height = len(rows) * ROW_HEIGHT
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">',
        f'<g font-family="{FONT_STACK}" font-size="{FONT_SIZE}">',
    ]
    for number, row in enumerate(rows):
        y = number * ROW_HEIGHT + BASELINE
        runs = []
        column = 0
        while column < len(row):
            colour = grid[number][column]
            if colour is None:
                column += 1
                continue
            start = column
            while column < len(row) and grid[number][column] == colour:
                column += 1
            runs.append((start, row[start:column], colour))
        if not runs:
            continue
        spans = []
        for start, chars, colour in runs:
            xs = " ".join(str((start + offset) * CELL_WIDTH) for offset in range(len(chars)))
            spans.append(f'<tspan x="{xs}" fill="{colour}">{escape(chars)}</tspan>')
        out.append(f'<text y="{y}">{"".join(spans)}</text>')
    out.append("</g>")
    out.append("</svg>")
    return "\n".join(out) + "\n"


def sibling_paths(drawing):
    directory = os.path.dirname(drawing)
    stem = os.path.splitext(os.path.basename(drawing))[0]
    return (
        os.path.join(directory, f"{stem}-colors.txt"),
        os.path.join(directory, f"{stem}.svg"),
    )


def read_text(path):
    try:
        with open(path, "r", encoding="ascii", newline="") as f:
            return f.read()
    except FileNotFoundError:
        raise BannerError(f"{path} not found")
    except UnicodeDecodeError:
        raise BannerError(f"{path} holds a character outside 7-bit ASCII")
    except OSError as error:
        raise BannerError(f"{path} could not be read: {error.strerror}")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Render the banner SVG from its plain-text drawing and colour mapping."
    )
    parser.add_argument(
        "drawing",
        nargs="?",
        default=DEFAULT_DRAWING,
        help=f"the plain-text drawing (default: {DEFAULT_DRAWING}); its colour mapping is "
        "<stem>-colors.txt beside it and the SVG is written beside both as <stem>.svg",
    )
    args = parser.parse_args(argv)
    colours_path, output_path = sibling_paths(args.drawing)
    try:
        svg = render(read_text(args.drawing), read_text(colours_path))
        with open(output_path, "w", encoding="ascii", newline="\n") as f:
            f.write(svg)
    except BannerError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    except OSError as error:
        print(f"Error: {output_path} could not be written: {error.strerror}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
