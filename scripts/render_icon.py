"""Render the VS Code extension's activity-bar icon SVG and listing icon PNG from two
plain-text arm drawings.

Usage: uv run scripts/render_icon.py

The icon is three octopus arms side by side: on the left and on the right a short arm cut
verbatim from the README banner's drawing, assets/banner.txt, its first arm and its last, a
mirrored pair whose curls point inward; in the centre the larger arm drawn on its own in
assets/icon-centre-arm.txt. The three are composed on one common character grid, so the
centre arm is larger by its own drawing alone and no arm is magnified. The SVG is written to
gurita-vscode/media/activity-bar.svg and the PNG to gurita-vscode/media/icon.png, the icon the
manifest's `icon` entry names for the listings; both committed icons are derived output of the
two drawings, regenerated by re-running this script and never edited by hand.

The listing icon is the same three arms in the same geometry, filled white on a filled square
of the banner's darker violet, #9333ea, 256 pixels on a side, the arms scaled uniformly to
leave a margin around them. The script rasterizes it itself, antialiased, and writes the PNG
through zlib and struct with no external tool; it computes the pixels with arithmetic and
square roots only, so every platform rasterizes the same image.

Both drawings are plain text, one grid row per line, using only the 95 printable 7-bit ASCII
characters (U+0020 to U+007E), the form scripts/render_banner.py reads. The banner is split
into its arms as the separate shapes its characters outline.

Each arm is drawn as one filled outline in one fill colour, with no character drawn as text:
its shape is every cell of the arm's drawing that is a character or a space enclosed by its
characters, the drawing's top edge taken as closed where the arm hangs from the body, and the
outline is the boundary of those cells with every corner rounded, so the brackets survive only
as the shape's edges and the arm tapers and curls as its drawing does. The centre arm keeps
each sucker, an `o` in its drawing, as a round hole cut out of the fill; the two side arms are
plain silhouettes. The output depends on the two input files alone, so every run writes the
same SVG and the same image; the PNG's compressed bytes depend also on the zlib build the
interpreter carries, so two builds may compress the same pixels differently.

This script is stdlib-only and runs under Python 3.9 and later. It only reads its two inputs
and writes its two outputs; it never invokes git.
"""

import argparse
import math
import os
import struct
import sys
import zlib

DEFAULT_BANNER = os.path.join("assets", "banner.txt")
DEFAULT_CENTRE = os.path.join("assets", "icon-centre-arm.txt")
DEFAULT_OUTPUT = os.path.join("gurita-vscode", "media", "activity-bar.svg")
DEFAULT_LISTING = os.path.join("gurita-vscode", "media", "icon.png")

CELL_WIDTH = 10
ROW_HEIGHT = 20
ARM_GAP = 1
ICON_SIZE = 24
FILL = "#d7dae0"
SUCKER = "o"
SUCKER_RADIUS = 7

LISTING_SIZE = 256
LISTING_MARGIN = 0.14
LISTING_FILL = "#ffffff"
LISTING_BACKGROUND = "#9333ea"
CURVE_STEPS = 16
SAMPLES = 16
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


class IconError(Exception):
    """A drawing cannot be rendered into the icon."""


def split_lines(text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def parse_drawing(text, name):
    rows = split_lines(text)
    while rows and not rows[-1].strip(" "):
        rows.pop()
    if not rows:
        raise IconError(f"{name} is empty")
    for number, row in enumerate(rows, 1):
        for column, char in enumerate(row, 1):
            if not " " <= char <= "~":
                raise IconError(
                    f"{name} row {number}, column {column}: {char!r} is not a printable "
                    "7-bit ASCII character (U+0020 to U+007E)"
                )
    width = max(len(row) for row in rows)
    return [row.ljust(width) for row in rows]


def trim(rows):
    """Cut a grid down to the rows and columns its characters occupy."""
    while rows and not rows[-1].strip(" "):
        rows = rows[:-1]
    while rows and not rows[0].strip(" "):
        rows = rows[1:]
    columns = [c for c in range(len(rows[0])) if any(row[c] != " " for row in rows)]
    return [row[columns[0]:columns[-1] + 1] for row in rows]


def split_arms(rows):
    """Split a drawing into its arms, left to right.

    An arm is one group of inside cells joined through edge-sharing neighbours; its grid holds
    the drawing's characters on those cells verbatim and a space everywhere else.
    """
    remaining = shape_cells(rows)
    arms = []
    while remaining:
        seed = min(remaining)
        group = set()
        stack = [seed]
        while stack:
            cell = stack.pop()
            if cell in group or cell not in remaining:
                continue
            group.add(cell)
            column, row = cell
            stack.extend(
                ((column + 1, row), (column - 1, row), (column, row + 1), (column, row - 1))
            )
        remaining -= group
        grid = [
            "".join(char if (column, row) in group else " " for column, char in enumerate(line))
            for row, line in enumerate(rows)
        ]
        arms.append(trim(grid))
    return arms


def shape_cells(arm):
    """Return the set of (column, row) cells inside the shape a drawing outlines.

    A cell is outside when a path of spaces joins it, through edge-sharing neighbours, to the
    grid's left, right, or bottom border; the top border is closed, since the arm hangs from
    there. Every other cell, character or enclosed space, is inside.
    """
    height = len(arm)
    width = len(arm[0])
    outside = set()
    stack = []
    for row in range(height):
        stack.append((0, row))
        stack.append((width - 1, row))
    for column in range(width):
        stack.append((column, height - 1))
    while stack:
        column, row = stack.pop()
        if (column, row) in outside or arm[row][column] != " ":
            continue
        outside.add((column, row))
        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nc, nr = column + dc, row + dr
            if 0 <= nc < width and 0 <= nr < height:
                stack.append((nc, nr))
    return {
        (column, row)
        for row in range(height)
        for column in range(width)
        if (column, row) not in outside
    }


# Travel directions on the grid, x to the right and y down, in clockwise order.
DIRECTIONS = ((1, 0), (0, 1), (-1, 0), (0, -1))


def boundary_loops(cells):
    """Trace the boundary of a set of cells as closed loops of grid points.

    Every loop runs clockwise on screen with the shape on its right. Where two inside cells
    touch only at a corner, the trace turns right there, so they stay apart.
    """
    edges = {}
    for column, row in cells:
        if (column, row - 1) not in cells:
            edges.setdefault((column, row), []).append((column + 1, row))
        if (column + 1, row) not in cells:
            edges.setdefault((column + 1, row), []).append((column + 1, row + 1))
        if (column, row + 1) not in cells:
            edges.setdefault((column + 1, row + 1), []).append((column, row + 1))
        if (column - 1, row) not in cells:
            edges.setdefault((column, row + 1), []).append((column, row))
    loops = []
    while edges:
        start = min(edges)
        loop = [start]
        point = start
        heading = None
        while True:
            targets = edges[point]
            if heading is None or len(targets) == 1:
                target = targets[0]
            else:
                def turn(candidate):
                    step = (candidate[0] - point[0], candidate[1] - point[1])
                    return (DIRECTIONS.index(step) - DIRECTIONS.index(heading)) % 4
                # A right turn first, then straight on, then a left turn.
                target = min(targets, key=lambda candidate: (1 - turn(candidate)) % 4)
            targets.remove(target)
            if not targets:
                del edges[point]
            heading = (target[0] - point[0], target[1] - point[1])
            point = target
            if point == start:
                break
            loop.append(point)
        loops.append(corners(loop))
    return loops


def corners(loop):
    """Drop the points of a closed loop that lie on a straight run between their neighbours."""
    kept = []
    for index, point in enumerate(loop):
        before = loop[index - 1]
        after = loop[(index + 1) % len(loop)]
        straight = (before[0] == point[0] == after[0]) or (before[1] == point[1] == after[1])
        if not straight:
            kept.append(point)
    return kept


def soften(loop):
    """Replace every horizontal side one cell long by its midpoint.

    A one-cell step between two rows is a slanted bracket's offset, so the outline runs
    through it on a slant rather than stepping, and the arm tapers and curls smoothly.
    """
    softened = []
    count = len(loop)
    index = 0
    skip_first = False
    while index < count:
        point = loop[index]
        after = loop[(index + 1) % count]
        if point[1] == after[1] and abs(point[0] - after[0]) == 1:
            softened.append(((point[0] + after[0]) / 2, point[1]))
            if index + 1 == count:
                skip_first = True
            index += 2
        else:
            softened.append(point)
            index += 1
    if skip_first:
        softened = softened[1:]
    return softened


def number(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def rounded_path(points):
    """Return path data for a closed polygon with every corner rounded.

    The curve passes through the midpoint of every side and bends at each corner along a
    quadratic curve that has the corner as its control point.
    """
    def midpoint(a, b):
        return ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)

    start = midpoint(points[-1], points[0])
    parts = [f"M{number(start[0])} {number(start[1])}"]
    for index, corner in enumerate(points):
        end = midpoint(corner, points[(index + 1) % len(points)])
        parts.append(
            f"Q{number(corner[0])} {number(corner[1])} {number(end[0])} {number(end[1])}"
        )
    parts.append("Z")
    return "".join(parts)


def hole_path(x, y, radius):
    """Return path data for a circle, to be cut out of the fill under the even-odd rule."""
    return (
        f"M{number(x - radius)} {number(y)}"
        f"a{number(radius)} {number(radius)} 0 1 0 {number(2 * radius)} 0"
        f"a{number(radius)} {number(radius)} 0 1 0 {number(-2 * radius)} 0Z"
    )


def arm_shape(arm, left, top, holes):
    """Return one arm's outline loops and sucker holes, its grid's top-left cell at (left, top).

    Each loop is the list of corner points the rounded outline bends at, and each hole a
    (centre x, centre y, radius) circle, all in the icon's drawing units.
    """
    loops = [
        [((left + c) * CELL_WIDTH, (top + r) * ROW_HEIGHT) for c, r in soften(loop)]
        for loop in boundary_loops(shape_cells(arm))
    ]
    circles = []
    if holes:
        for row, line in enumerate(arm):
            for column, char in enumerate(line):
                if char == SUCKER:
                    circles.append(
                        (
                            (left + column + 0.5) * CELL_WIDTH,
                            (top + row + 0.5) * ROW_HEIGHT,
                            SUCKER_RADIUS,
                        )
                    )
    return loops, circles


def compose(banner_text, centre_text):
    """Lay the three arms out on one square, returning its side and each arm's shape.

    The side is in the icon's drawing units and each arm's shape is the pair arm_shape
    returns, so the SVG and the PNG are drawn from the same geometry.
    """
    banner_arms = split_arms(parse_drawing(banner_text, "the banner drawing"))
    if len(banner_arms) < 2:
        raise IconError("the banner drawing holds fewer than two arms")
    centre = trim(parse_drawing(centre_text, "the centre arm drawing"))
    layout = [(banner_arms[0], False), (centre, True), (banner_arms[-1], False)]
    columns = sum(len(arm[0]) for arm, _ in layout) + ARM_GAP * (len(layout) - 1)
    rows = max(len(arm) for arm, _ in layout)
    width = columns * CELL_WIDTH
    height = rows * ROW_HEIGHT
    side = max(width, height)
    left = (side - width) / 2 / CELL_WIDTH
    top = (side - height) / 2 / ROW_HEIGHT
    shapes = []
    for arm, holes in layout:
        shapes.append(arm_shape(arm, left, top, holes))
        left += len(arm[0]) + ARM_GAP
    return side, shapes


def render(banner_text, centre_text):
    """Return the icon SVG for the banner's drawing and the centre arm's drawing, as text."""
    side, shapes = compose(banner_text, centre_text)
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{ICON_SIZE}" height="{ICON_SIZE}" '
        f'viewBox="0 0 {side} {side}">',
    ]
    for loops, circles in shapes:
        data = "".join(rounded_path(points) for points in loops) + "".join(
            hole_path(x, y, radius) for x, y, radius in circles
        )
        out.append(f'<path fill="{FILL}" fill-rule="evenodd" d="{data}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def flatten(points, scale, offset):
    """Return the rounded outline through the given corners as a polygon in pixels.

    The outline is the one rounded_path draws: from the midpoint of each side to the next
    along a quadratic curve with the corner between them as its control point, each curve cut
    into CURVE_STEPS straight pieces.
    """
    def pixel(point):
        return (offset + point[0] * scale, offset + point[1] * scale)

    def midpoint(a, b):
        return ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)

    polygon = []
    start = pixel(midpoint(points[-1], points[0]))
    for index, corner in enumerate(points):
        control = pixel(corner)
        end = pixel(midpoint(corner, points[(index + 1) % len(points)]))
        for step in range(1, CURVE_STEPS + 1):
            t = step / CURVE_STEPS
            u = 1 - t
            polygon.append(
                (
                    u * u * start[0] + 2 * u * t * control[0] + t * t * end[0],
                    u * u * start[1] + 2 * u * t * control[1] + t * t * end[1],
                )
            )
        start = end
    return polygon


def coverage(edges, circles, size):
    """Return, row by row, the fraction of every pixel the shapes cover under the even-odd rule.

    Each pixel row is sampled along SAMPLES horizontal lines; along each line the covered
    spans are found from where the polygon edges and the circles cross it, and each pixel takes
    the exact length of span it holds, so the result is antialiased in both directions. Only
    arithmetic and square roots are used, so every platform computes the same fractions.
    """
    lines = size * SAMPLES
    buckets = [[] for _ in range(lines)]
    for x0, y0, x1, y1 in edges:
        if y0 == y1:
            continue
        if y0 > y1:
            x0, y0, x1, y1 = x1, y1, x0, y0
        slope = (x1 - x0) / (y1 - y0)
        first = max(0, math.ceil(y0 * SAMPLES - 0.5))
        last = min(lines, math.ceil(y1 * SAMPLES - 0.5))
        for line in range(first, last):
            buckets[line].append((x0, y0, slope))
    rows = []
    for row in range(size):
        cover = [0.0] * size
        for line in range(row * SAMPLES, (row + 1) * SAMPLES):
            y = (line + 0.5) / SAMPLES
            crossings = [x0 + (y - y0) * slope for x0, y0, slope in buckets[line]]
            for cx, cy, radius in circles:
                dy = y - cy
                if dy * dy < radius * radius:
                    half = math.sqrt(radius * radius - dy * dy)
                    crossings.append(cx - half)
                    crossings.append(cx + half)
            if len(crossings) % 2:
                raise IconError("an outline does not close")
            crossings.sort()
            for index in range(0, len(crossings), 2):
                a = min(max(crossings[index], 0.0), float(size))
                b = min(max(crossings[index + 1], 0.0), float(size))
                if b <= a:
                    continue
                ia = int(a)
                ib = int(b)
                if ia == ib:
                    if ia < size:
                        cover[ia] += b - a
                    continue
                cover[ia] += ia + 1 - a
                for column in range(ia + 1, ib):
                    cover[column] += 1.0
                if ib < size:
                    cover[ib] += b - ib
        rows.append([min(value / SAMPLES, 1.0) for value in cover])
    return rows


def hex_colour(text):
    return tuple(int(text[index:index + 2], 16) for index in (1, 3, 5))


def png_chunk(kind, data):
    return (
        struct.pack(">I", len(data))
        + kind
        + data
        + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    )


def render_png(banner_text, centre_text):
    """Return the listing icon PNG for the banner's drawing and the centre arm's, as bytes.

    The arms are filled in LISTING_FILL on a square of LISTING_BACKGROUND, LISTING_SIZE
    pixels on a side, in the SVG's geometry scaled uniformly to leave LISTING_MARGIN of the
    side clear on every edge. The image is 8-bit RGB with no alpha, every row unfiltered.
    """
    side, shapes = compose(banner_text, centre_text)
    size = LISTING_SIZE
    offset = size * LISTING_MARGIN
    scale = (size - 2 * offset) / side
    edges = []
    circles = []
    for loops, holes in shapes:
        for points in loops:
            polygon = flatten(points, scale, offset)
            for index, start in enumerate(polygon):
                end = polygon[(index + 1) % len(polygon)]
                edges.append((start[0], start[1], end[0], end[1]))
        for x, y, radius in holes:
            circles.append((offset + x * scale, offset + y * scale, radius * scale))
    background = hex_colour(LISTING_BACKGROUND)
    fill = hex_colour(LISTING_FILL)
    raw = bytearray()
    for cover in coverage(edges, circles, size):
        raw.append(0)
        for value in cover:
            for back, front in zip(background, fill):
                raw.append(int(back + (front - back) * value + 0.5))
    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return (
        PNG_SIGNATURE
        + png_chunk(b"IHDR", header)
        + png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + png_chunk(b"IEND", b"")
    )


def read_text(path):
    try:
        with open(path, "r", encoding="ascii", newline="") as f:
            return f.read()
    except FileNotFoundError:
        raise IconError(f"{path} not found")
    except UnicodeDecodeError:
        raise IconError(f"{path} holds a character outside 7-bit ASCII")
    except OSError as error:
        raise IconError(f"{path} could not be read: {error.strerror}")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Render the activity-bar icon SVG and the listing icon PNG from the "
        f"banner's drawing and the centre arm's drawing, writing {DEFAULT_OUTPUT} and "
        f"{DEFAULT_LISTING}."
    )
    parser.parse_args(argv)
    try:
        banner_text = read_text(DEFAULT_BANNER)
        centre_text = read_text(DEFAULT_CENTRE)
        svg = render(banner_text, centre_text)
        png = render_png(banner_text, centre_text)
    except IconError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    for path, mode, content in ((DEFAULT_OUTPUT, "w", svg), (DEFAULT_LISTING, "wb", png)):
        try:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if mode == "w":
                with open(path, mode, encoding="ascii", newline="\n") as f:
                    f.write(content)
            else:
                with open(path, mode) as f:
                    f.write(content)
        except OSError as error:
            print(f"Error: {path} could not be written: {error.strerror}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
