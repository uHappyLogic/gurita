"""Render the VS Code extension's activity-bar icon SVG from two plain-text arm drawings.

Usage: uv run scripts/render_icon.py

The icon is three octopus arms side by side: on the left and on the right a short arm cut
verbatim from the README banner's drawing, assets/banner.txt, its first arm and its last, a
mirrored pair whose curls point inward; in the centre the larger arm drawn on its own in
assets/icon-centre-arm.txt. The three are composed on one common character grid, so the
centre arm is larger by its own drawing alone and no arm is magnified. The SVG is written to
gurita-vscode/media/activity-bar.svg, the committed icon being derived output of the two
drawings, regenerated by re-running this script and never edited by hand.

Both drawings are plain text, one grid row per line, using only the 95 printable 7-bit ASCII
characters (U+0020 to U+007E), the form scripts/render_banner.py reads. The banner is split
into its arms as the separate shapes its characters outline.

Each arm is drawn as one filled outline in one fill colour, with no character drawn as text:
its shape is every cell of the arm's drawing that is a character or a space enclosed by its
characters, the drawing's top edge taken as closed where the arm hangs from the body, and the
outline is the boundary of those cells with every corner rounded, so the brackets survive only
as the shape's edges and the arm tapers and curls as its drawing does. The centre arm keeps
each sucker, an `o` in its drawing, as a round hole cut out of the fill; the two side arms are
plain silhouettes. The output depends on the two input files alone, so every run writes the
same bytes.

This script is stdlib-only and runs under Python 3.9 and later. It only reads its two inputs
and writes its one output; it never invokes git.
"""

import argparse
import os
import sys

DEFAULT_BANNER = os.path.join("assets", "banner.txt")
DEFAULT_CENTRE = os.path.join("assets", "icon-centre-arm.txt")
DEFAULT_OUTPUT = os.path.join("gurita-vscode", "media", "activity-bar.svg")

CELL_WIDTH = 10
ROW_HEIGHT = 20
ARM_GAP = 1
ICON_SIZE = 24
FILL = "#d7dae0"
SUCKER = "o"
SUCKER_RADIUS = 7


class IconError(Exception):
    """A drawing cannot be rendered into the icon."""


def split_lines(text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def parse_drawing(text, name):
    rows = split_lines(text)
    while rows and not rows[-1].strip(" "):
        rows.pop()
    if not rows:
        raise IconError(f"{name} is empty")
    for number, row in enumerate(rows, 1):
        for column, char in enumerate(row, 1):
            if not " " <= char <= "~":
                raise IconError(
                    f"{name} row {number}, column {column}: {char!r} is not a printable "
                    "7-bit ASCII character (U+0020 to U+007E)"
                )
    width = max(len(row) for row in rows)
    return [row.ljust(width) for row in rows]


def trim(rows):
    """Cut a grid down to the rows and columns its characters occupy."""
    while rows and not rows[-1].strip(" "):
        rows = rows[:-1]
    while rows and not rows[0].strip(" "):
        rows = rows[1:]
    columns = [c for c in range(len(rows[0])) if any(row[c] != " " for row in rows)]
    return [row[columns[0]:columns[-1] + 1] for row in rows]


def split_arms(rows):
    """Split a drawing into its arms, left to right.

    An arm is one group of inside cells joined through edge-sharing neighbours; its grid holds
    the drawing's characters on those cells verbatim and a space everywhere else.
    """
    remaining = shape_cells(rows)
    arms = []
    while remaining:
        seed = min(remaining)
        group = set()
        stack = [seed]
        while stack:
            cell = stack.pop()
            if cell in group or cell not in remaining:
                continue
            group.add(cell)
            column, row = cell
            stack.extend(
                ((column + 1, row), (column - 1, row), (column, row + 1), (column, row - 1))
            )
        remaining -= group
        grid = [
            "".join(char if (column, row) in group else " " for column, char in enumerate(line))
            for row, line in enumerate(rows)
        ]
        arms.append(trim(grid))
    return arms


def shape_cells(arm):
    """Return the set of (column, row) cells inside the shape a drawing outlines.

    A cell is outside when a path of spaces joins it, through edge-sharing neighbours, to the
    grid's left, right, or bottom border; the top border is closed, since the arm hangs from
    there. Every other cell, character or enclosed space, is inside.
    """
    height = len(arm)
    width = len(arm[0])
    outside = set()
    stack = []
    for row in range(height):
        stack.append((0, row))
        stack.append((width - 1, row))
    for column in range(width):
        stack.append((column, height - 1))
    while stack:
        column, row = stack.pop()
        if (column, row) in outside or arm[row][column] != " ":
            continue
        outside.add((column, row))
        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nc, nr = column + dc, row + dr
            if 0 <= nc < width and 0 <= nr < height:
                stack.append((nc, nr))
    return {
        (column, row)
        for row in range(height)
        for column in range(width)
        if (column, row) not in outside
    }


# Travel directions on the grid, x to the right and y down, in clockwise order.
DIRECTIONS = ((1, 0), (0, 1), (-1, 0), (0, -1))


def boundary_loops(cells):
    """Trace the boundary of a set of cells as closed loops of grid points.

    Every loop runs clockwise on screen with the shape on its right. Where two inside cells
    touch only at a corner, the trace turns right there, so they stay apart.
    """
    edges = {}
    for column, row in cells:
        if (column, row - 1) not in cells:
            edges.setdefault((column, row), []).append((column + 1, row))
        if (column + 1, row) not in cells:
            edges.setdefault((column + 1, row), []).append((column + 1, row + 1))
        if (column, row + 1) not in cells:
            edges.setdefault((column + 1, row + 1), []).append((column, row + 1))
        if (column - 1, row) not in cells:
            edges.setdefault((column, row + 1), []).append((column, row))
    loops = []
    while edges:
        start = min(edges)
        loop = [start]
        point = start
        heading = None
        while True:
            targets = edges[point]
            if heading is None or len(targets) == 1:
                target = targets[0]
            else:
                def turn(candidate):
                    step = (candidate[0] - point[0], candidate[1] - point[1])
                    return (DIRECTIONS.index(step) - DIRECTIONS.index(heading)) % 4
                # A right turn first, then straight on, then a left turn.
                target = min(targets, key=lambda candidate: (1 - turn(candidate)) % 4)
            targets.remove(target)
            if not targets:
                del edges[point]
            heading = (target[0] - point[0], target[1] - point[1])
            point = target
            if point == start:
                break
            loop.append(point)
        loops.append(corners(loop))
    return loops


def corners(loop):
    """Drop the points of a closed loop that lie on a straight run between their neighbours."""
    kept = []
    for index, point in enumerate(loop):
        before = loop[index - 1]
        after = loop[(index + 1) % len(loop)]
        straight = (before[0] == point[0] == after[0]) or (before[1] == point[1] == after[1])
        if not straight:
            kept.append(point)
    return kept


def soften(loop):
    """Replace every horizontal side one cell long by its midpoint.

    A one-cell step between two rows is a slanted bracket's offset, so the outline runs
    through it on a slant rather than stepping, and the arm tapers and curls smoothly.
    """
    softened = []
    count = len(loop)
    index = 0
    skip_first = False
    while index < count:
        point = loop[index]
        after = loop[(index + 1) % count]
        if point[1] == after[1] and abs(point[0] - after[0]) == 1:
            softened.append(((point[0] + after[0]) / 2, point[1]))
            if index + 1 == count:
                skip_first = True
            index += 2
        else:
            softened.append(point)
            index += 1
    if skip_first:
        softened = softened[1:]
    return softened


def number(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def rounded_path(points):
    """Return path data for a closed polygon with every corner rounded.

    The curve passes through the midpoint of every side and bends at each corner along a
    quadratic curve that has the corner as its control point.
    """
    def midpoint(a, b):
        return ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)

    start = midpoint(points[-1], points[0])
    parts = [f"M{number(start[0])} {number(start[1])}"]
    for index, corner in enumerate(points):
        end = midpoint(corner, points[(index + 1) % len(points)])
        parts.append(
            f"Q{number(corner[0])} {number(corner[1])} {number(end[0])} {number(end[1])}"
        )
    parts.append("Z")
    return "".join(parts)


def hole_path(x, y, radius):
    """Return path data for a circle, to be cut out of the fill under the even-odd rule."""
    return (
        f"M{number(x - radius)} {number(y)}"
        f"a{number(radius)} {number(radius)} 0 1 0 {number(2 * radius)} 0"
        f"a{number(radius)} {number(radius)} 0 1 0 {number(-2 * radius)} 0Z"
    )


def arm_path(arm, left, top, holes):
    """Return path data for one arm whose grid's top-left cell sits at (left, top)."""
    parts = []
    for loop in boundary_loops(shape_cells(arm)):
        points = [((left + c) * CELL_WIDTH, (top + r) * ROW_HEIGHT) for c, r in soften(loop)]
        parts.append(rounded_path(points))
    if holes:
        for row, line in enumerate(arm):
            for column, char in enumerate(line):
                if char == SUCKER:
                    parts.append(
                        hole_path(
                            (left + column + 0.5) * CELL_WIDTH,
                            (top + row + 0.5) * ROW_HEIGHT,
                            SUCKER_RADIUS,
                        )
                    )
    return "".join(parts)


def render(banner_text, centre_text):
    """Return the icon SVG for the banner's drawing and the centre arm's drawing, as text."""
    banner_arms = split_arms(parse_drawing(banner_text, "the banner drawing"))
    if len(banner_arms) < 2:
        raise IconError("the banner drawing holds fewer than two arms")
    centre = trim(parse_drawing(centre_text, "the centre arm drawing"))
    layout = [(banner_arms[0], False), (centre, True), (banner_arms[-1], False)]
    columns = sum(len(arm[0]) for arm, _ in layout) + ARM_GAP * (len(layout) - 1)
    rows = max(len(arm) for arm, _ in layout)
    width = columns * CELL_WIDTH
    height = rows * ROW_HEIGHT
    side = max(width, height)
    left = (side - width) / 2 / CELL_WIDTH
    top = (side - height) / 2 / ROW_HEIGHT
    paths = []
    for arm, holes in layout:
        paths.append(arm_path(arm, left, top, holes))
        left += len(arm[0]) + ARM_GAP
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{ICON_SIZE}" height="{ICON_SIZE}" '
        f'viewBox="0 0 {side} {side}">',
    ]
    for data in paths:
        out.append(f'<path fill="{FILL}" fill-rule="evenodd" d="{data}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def read_text(path):
    try:
        with open(path, "r", encoding="ascii", newline="") as f:
            return f.read()
    except FileNotFoundError:
        raise IconError(f"{path} not found")
    except UnicodeDecodeError:
        raise IconError(f"{path} holds a character outside 7-bit ASCII")
    except OSError as error:
        raise IconError(f"{path} could not be read: {error.strerror}")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Render the activity-bar icon SVG from the banner's drawing and the "
        f"centre arm's drawing, writing {DEFAULT_OUTPUT}."
    )
    parser.parse_args(argv)
    try:
        svg = render(read_text(DEFAULT_BANNER), read_text(DEFAULT_CENTRE))
        os.makedirs(os.path.dirname(DEFAULT_OUTPUT), exist_ok=True)
        with open(DEFAULT_OUTPUT, "w", encoding="ascii", newline="\n") as f:
            f.write(svg)
    except IconError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    except OSError as error:
        print(f"Error: {DEFAULT_OUTPUT} could not be written: {error.strerror}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
